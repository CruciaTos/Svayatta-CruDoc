"""segment_odontogram.py - one-off: finds every tooth in the two odontogram pictures and writes
lib/features/dental/presentation/desktop/chart/odontogram_regions.dart (smooth outline + centre per FDI, in
image pixels, plus the image size) and debug pictures in dental3d/tmp/chart2d/regions_{2d,3d}.png.

Pictures: assets/images/odontogram/odontogram_2d.jpg (black line art) and odontogram_3d.jpg (grey clay).
Run (system python; Pillow, numpy, scipy, scikit-image, OpenCV):  python tool/odontogram/segment_odontogram.py

Method: 2D - the line art's enclosed shapes are the teeth (32 blobs). 3D - the tooth mask is what the neon edge
picture (white outlines on black, dental3d/tmp/chart2d/odontogram_3d_neon.jpg, used only here, not shipped) encloses,
merged with the clay-vs-white mask; touching teeth are cut by a watershed with one marker per tooth (distance-
transform peaks, missing ones added where the mask is not covered yet) over distance + neon edges.
Then: the upper arch is the top half, the lower arch the bottom half; teeth are numbered from the midline outwards,
picture left = patient's right (11-18, 41-48), picture right = patient's left (21-28, 31-38). Outlines are
sub-pixel marching-squares contours of each blurred region, smoothed and resampled to POINTS points.
"""
import os

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage as ndi

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
IMG_DIR = os.path.join(ROOT, 'assets', 'images', 'odontogram')
OUT_DART = os.path.join(ROOT, 'lib', 'features', 'dental', 'presentation', 'desktop', 'chart',
                        'odontogram_regions.dart')
DEBUG_DIR = os.path.join(ROOT, 'dental3d', 'tmp', 'chart2d')
NEON_3D = os.path.join(DEBUG_DIR, 'odontogram_3d_neon.jpg')
POINTS = 160
LAND_B = 6.0     # weight of the boundary evidence in the watershed landscape
LAND_D = 0.05    # weight of the distance-to-edge (necks) term
NL = '\n'

HEAD = NL.join([
    "// GENERATED by tool/odontogram/segment_odontogram.py. Do not edit.",
    "// Odontogram artwork used with the owner's permission.",
    "import 'dart:ui';",
    "",
    "/// One tooth in an odontogram picture, in the picture's pixels.",
    "class OdontogramRegion {",
    "  const OdontogramRegion(this.center, this.radius, this.points);",
    "",
    "  /// The deepest point inside the tooth (where its number goes).",
    "  final Offset center;",
    "",
    "  /// Distance from [center] to the nearest edge.",
    "  final double radius;",
    "",
    "  /// The tooth's smooth outline as x, y, x, y ... (closed, in order).",
    "  final List<double> points;",
    "",
    "  /// The outline as points.",
    "  List<Offset> get outline => [",
    "    for (var i = 0; i + 1 < points.length; i += 2) Offset(points[i], points[i + 1]),",
    "  ];",
    "}",
    "",
    "",
])


def mask_2d(rgb):
    """Line art: dark pixels are lines; everything not reachable from the border without crossing a line is
    inside a tooth. Returns the filled tooth mask."""
    g = rgb.mean(axis=2)
    lines = ndi.binary_dilation(g < 150, iterations=1)       # close hairline gaps in the outlines
    lab, _ = ndi.label(~lines)
    border = set(np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]]))) - {0}
    return ~np.isin(lab, list(border))


def _gray(name, w, h, blur=1.5):
    """A filtered version of the clay picture (same alignment), normalised to 0..1, slightly blurred."""
    g = np.asarray(Image.open(os.path.join(DEBUG_DIR, name)).convert('L').resize((w, h), Image.LANCZOS)).astype(float)
    g = ndi.gaussian_filter(g, blur)
    return np.clip(g / max(np.percentile(g, 99.5), 1), 0, 1)


def aligned_outlines(w, h, clay_mask):
    """The white-outline map (every tooth a closed outline, contacts included), warped (small affine from ECC on the
    silhouettes) onto the clay picture, normalised 0..1."""
    import cv2
    g = np.asarray(Image.open(os.path.join(DEBUG_DIR, 'odontogram_3d_outlines17.png')).convert('L')
                   .resize((w, h), Image.LANCZOS)).astype(np.float32)
    g[int(h * 0.93):, int(w * 0.85):] = 0                      # the sparkle mark
    lab, _ = ndi.label(~ndi.binary_dilation(g > 80, iterations=1))
    out = {lab[0, 0], lab[h // 2, w // 2]} - {0}
    sil = ndi.binary_erosion(~np.isin(lab, list(out)), iterations=3)
    a = ndi.gaussian_filter(clay_mask.astype(np.float32), 4)
    b = ndi.gaussian_filter(sil.astype(np.float32), 4)
    m = np.eye(2, 3, dtype=np.float32)
    _, m = cv2.findTransformECC(a, b, m, cv2.MOTION_AFFINE,
                                (cv2.TERM_CRITERIA_EPS | cv2.TERM_CRITERIA_COUNT, 200, 1e-7), None, 5)
    g = cv2.warpAffine(g, m, (w, h), flags=cv2.INTER_LINEAR + cv2.WARP_INVERSE_MAP)
    g = ndi.gaussian_filter(g, 1.0)
    return np.clip(g / max(np.percentile(g, 99.5), 1), 0, 1)


def boundary_map(w, h, clay_mask):
    """How strongly each pixel looks like a tooth boundary (0..1): the edge maps and the rim-light pictures
    (bright rims), plus the dark crescents of the black-and-white threshold picture."""
    edges = _gray('odontogram_3d_edges_white.jpg', w, h)
    neon = _gray('odontogram_3d_neon.jpg', w, h)
    rim = _gray('odontogram_3d_rim_dark.jpg', w, h)
    cyan = _gray('odontogram_3d_rim_cyan.jpg', w, h)
    thr = np.asarray(Image.open(os.path.join(DEBUG_DIR, 'odontogram_3d_threshold.jpg')).convert('L')
                     .resize((w, h), Image.LANCZOS)).astype(float) / 255.0
    crescents = ndi.gaussian_filter(1 - thr, 1.5)
    # crescents only count where they are thin dark bands next to white paper-like areas of the picture; the
    # paper itself is white (1 - thr = 0), so what remains is the dark rims and fissures
    others = np.clip(0.30 * edges + 0.20 * neon + 0.25 * rim + 0.25 * cyan + 0.6 * crescents, 0, 1)
    return np.clip(0.75 * aligned_outlines(w, h, clay_mask) + 0.25 * others, 0, 1)


def apply_hand_cuts(lab):
    """Last-resort cuts: for a pair of FDI-less region ids this is done after numbering, see HAND_CUTS."""
    return lab


def segment_3d(rgb):
    """Labels (1..32) of the clay picture's teeth (see the module doc)."""
    from skimage.feature import peak_local_max
    from skimage.segmentation import watershed
    h, w = rgb.shape[:2]
    clay = rgb.astype(float).mean(axis=2)
    neon = np.asarray(Image.open(NEON_3D).convert('L').resize((w, h), Image.LANCZOS)).astype(float)
    # the region the neon outline encloses (not the open middle of the arches, not the outside)
    outline = ndi.binary_dilation(neon > 90, iterations=1)
    lab, _ = ndi.label(~outline)
    outside = {lab[0, 0], lab[h // 2, w // 2]} - {0}
    mask = ndi.binary_erosion(~np.isin(lab, list(outside)), iterations=1)
    mask |= ndi.gaussian_filter(clay, 1) < 240
    mask = ndi.binary_opening(mask, iterations=2)
    edt = ndi.distance_transform_edt(mask)
    dist = ndi.gaussian_filter(edt, 3)
    pk = peak_local_max(dist, min_distance=45, labels=mask.astype(int), num_peaks=40, exclude_border=False)
    seeds = [(int(y), int(x)) for y, x in pk][:32]
    yy, xx = np.mgrid[:h, :w]
    while len(seeds) < 32:                       # a narrow tooth beside wider ones has no peak of its own
        covered = np.zeros_like(mask)
        for y, x in seeds:
            r = 1.35 * edt[y, x]
            covered |= (yy - y) ** 2 + (xx - x) ** 2 < r * r
        rd = np.where(mask & ~covered, dist, 0)
        seeds.append(tuple(int(v) for v in np.unravel_index(np.argmax(rd), rd.shape)))
    markers = np.zeros(mask.shape, np.int32)
    for i, (y, x) in enumerate(seeds):
        markers[y - 3:y + 4, x - 3:x + 4] = i + 1
    land = LAND_B * boundary_map(w, h, mask) - LAND_D * ndi.gaussian_filter(edt, 2)
    lab = watershed(land, markers, mask=mask)
    return apply_hand_cuts(lab), 32


def split(mask, expected, min_area, min_distance=10, sigma=1.5):
    """Label the blobs of mask; touching teeth are split by a distance-transform watershed whose seeds are the
    `expected` strongest distance peaks (at least min_distance px apart)."""
    from skimage.feature import peak_local_max
    from skimage.segmentation import watershed
    lab, n = ndi.label(mask)
    areas = ndi.sum(mask, lab, range(1, n + 1))
    m = np.isin(lab, [i + 1 for i, a in enumerate(areas) if a >= min_area])
    lab, n = ndi.label(m)
    if n >= expected:
        return lab, n
    dist = ndi.gaussian_filter(ndi.distance_transform_edt(m), sigma)
    pk = peak_local_max(dist, min_distance=min_distance, labels=m.astype(int), num_peaks=expected,
                        exclude_border=False)
    markers = np.zeros(m.shape, np.int32)
    for i, (y, x) in enumerate(pk):
        markers[y, x] = i + 1
    out = watershed(-dist, markers, mask=m)
    return out, int(out.max())


def assign_fdi(lab):
    """{region id: fdi}: the 16 regions with the smallest centroid y are the upper arch; each arch splits at the
    picture's midline (left = patient's right) and is numbered from the front teeth outwards."""
    ids = list(range(1, lab.max() + 1))
    cen = {i: tuple(np.mean(np.nonzero(lab == i), axis=1)) for i in ids}      # (y, x)
    n_up = len(ids) // 2
    by_y = sorted(ids, key=lambda i: cen[i][0])
    arches = {'upper': by_y[:n_up], 'lower': by_y[n_up:]}
    mid = np.mean([cen[i][1] for i in ids])
    out = {}
    for arch, members in arches.items():
        left = [i for i in members if cen[i][1] < mid]
        right = [i for i in members if cen[i][1] >= mid]
        assert len(left) == len(right) == n_up // 2, (arch, len(left), len(right))
        front_first = (lambda i: cen[i][0]) if arch == 'upper' else (lambda i: -cen[i][0])
        for side, q in ((left, 1 if arch == 'upper' else 4), (right, 2 if arch == 'upper' else 3)):
            for k, i in enumerate(sorted(side, key=front_first)):
                out[i] = q * 10 + k + 1
    return out


def region_polygon(mask, n_points=POINTS):
    """Smooth sub-pixel outline: marching squares on the blurred region, Gaussian-smoothed along the contour,
    resampled evenly to n_points. Returns an (n, 2) array of (x, y) pixels."""
    from skimage.measure import find_contours
    pad = 8
    soft = ndi.gaussian_filter(np.pad(mask.astype(float), pad), 1.4)
    c = max(find_contours(soft, 0.5), key=len)[:-1] - pad       # (row, col)
    closed = np.vstack([c, c[:1]])
    seg = np.hypot(*np.diff(closed, axis=0).T)
    t = np.concatenate([[0], np.cumsum(seg)])
    dense_t = np.arange(0, t[-1], 1.0)                           # one point per pixel of contour
    cx = ndi.gaussian_filter1d(np.interp(dense_t, t, closed[:, 1]), 3.5, mode='wrap')
    cy = ndi.gaussian_filter1d(np.interp(dense_t, t, closed[:, 0]), 3.5, mode='wrap')
    idx = np.linspace(0, len(cx), n_points, endpoint=False).astype(int)
    return np.stack([cx[idx], cy[idx]], axis=1)


def debug_png(rgb, polys, path):
    """Translucent filled regions, the smooth outlines and the FDI numbers over the picture (2x)."""
    im = Image.fromarray(rgb).convert('RGBA').resize((rgb.shape[1] * 2, rgb.shape[0] * 2), Image.LANCZOS)
    rng = np.random.RandomState(3)
    over = Image.new('RGBA', im.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(over)
    for fdi, pts in sorted(polys.items()):
        col = tuple(int(v) for v in rng.randint(60, 255, 3))
        xy = [(float(x) * 2, float(y) * 2) for x, y in pts]
        d.polygon(xy, fill=col + (90,))
        d.line(xy + [xy[0]], fill=(255, 0, 0, 255), width=2)
        cx, cy = np.mean(xy, axis=0)
        d.text((cx - 8, cy - 5), str(fdi), fill=(0, 0, 0, 255))
    Image.alpha_composite(im, over).convert('RGB').save(path)


def contact_sheet(rgb, lab, fdis, polys, path, half=64, zoom=4, cols=6):
    """One zoomed crop of the clay picture per pair of touching teeth, both outlines drawn."""
    ids = sorted(fdis, key=lambda i: fdis[i])
    pairs = []
    for a in ids:
        grown = ndi.binary_dilation(lab == a, iterations=3)
        for b in ids:
            if fdis[b] > fdis[a] and (grown & (lab == b)).any():
                ys, xs = np.nonzero(grown & (lab == b))
                pairs.append((fdis[a], fdis[b], int(xs.mean()), int(ys.mean())))
    size = 2 * half * zoom
    rows = (len(pairs) + cols - 1) // cols
    sheet = Image.new('RGB', (cols * size, rows * size), 'white')
    base = Image.fromarray(rgb)
    for k, (fa, fb, cx, cy) in enumerate(pairs):
        x0, y0 = cx - half, cy - half
        crop = base.crop((x0, y0, x0 + 2 * half, y0 + 2 * half)).resize((size, size), Image.LANCZOS)
        d = ImageDraw.Draw(crop)
        for f, col in ((fa, (255, 0, 0)), (fb, (0, 90, 255))):
            xy = [((float(x) - x0) * zoom, (float(y) - y0) * zoom) for x, y in polys[f]]
            d.line(xy + [xy[0]], fill=col, width=2)
        d.text((6, 4), f'{fa} | {fb}', fill=(0, 0, 0))
        sheet.paste(crop, ((k % cols) * size, (k // cols) * size))
    sheet.save(path)
    print('contact pairs', len(pairs))


def main():
    os.makedirs(DEBUG_DIR, exist_ok=True)
    chunks = []
    for style, fn in (('2d', 'odontogram_2d.jpg'), ('3d', 'odontogram_3d.jpg')):
        rgb = np.asarray(Image.open(os.path.join(IMG_DIR, fn)).convert('RGB'))
        h, w = rgb.shape[:2]
        if style == '3d':
            lab, n = segment_3d(rgb)
        else:
            lab, n = split(mask_2d(rgb), 32, 0.0004 * h * w)
        assert n == 32, (style, n)
        fdis = assign_fdi(lab)
        rows = []
        polys = {}
        for i, fdi in sorted(fdis.items(), key=lambda kv: kv[1]):
            mk = lab == i
            dist = ndi.gaussian_filter(ndi.distance_transform_edt(mk), 2.0)
            cy, cx = np.unravel_index(np.argmax(dist), dist.shape)
            pts = region_polygon(mk)
            polys[fdi] = pts
            flat = ', '.join(f'{v:.1f}' for v in pts.ravel())
            rows.append(f'  {fdi}: OdontogramRegion(Offset({cx}, {cy}), {dist[cy, cx]:.1f}, [{flat}]),')
            print(style, fdi, len(pts), 'pts, area', int(mk.sum()))
        debug_png(rgb, polys, os.path.join(DEBUG_DIR, f'regions_{style}.png'))
        if style == '3d':
            contact_sheet(rgb, lab, fdis, polys, os.path.join(DEBUG_DIR, 'contacts_3d.png'))
        S = style.upper()
        chunks.append(
            f'/// Picture size in pixels.{NL}const Size odontogram{S}Size = Size({w}, {h});{NL}{NL}'
            f"/// The {S} picture's teeth, by FDI number (pixels of the picture).{NL}"
            f'const Map<int, OdontogramRegion> odontogram{S}Regions = {{{NL}' + NL.join(rows) + f'{NL}}};{NL}'
        )
    with open(OUT_DART, 'w', encoding='utf8', newline='\n') as f:
        f.write(HEAD + NL.join(chunks))
    print('wrote', OUT_DART)


if __name__ == '__main__':
    main()
