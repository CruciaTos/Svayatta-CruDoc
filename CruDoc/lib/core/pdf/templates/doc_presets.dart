/// Without a logo, blocks in [slide] move by (dx, dy) into its empty
/// space, and blocks in [onlyWith] (a tile behind the logo) are not drawn.
List<DocBlock> _logoAware(
  List<DocBlock> blocks, {
  Set<String> slide = const {},
  double dx = 0,
  double dy = 0,
  Set<String> onlyWith = const {},
}) => [
  for (final b in blocks)
    if (slide.contains(b.id))
      b.copyWith(noLogoDx: dx, noLogoDy: dy)
    else if (onlyWith.contains(b.id))
      b.copyWith(onlyWithLogo: true)
    else
      b,
];

