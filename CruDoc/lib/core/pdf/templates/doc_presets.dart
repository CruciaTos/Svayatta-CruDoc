DocBlock _f(
  String id,
  String field,
  double x,
  double y,
  double w,
  double h, {
  double pt = 9,
  bool bold = false,
  DocAlign align = DocAlign.left,
  String color = 'text',
  DocZone zone = DocZone.header,
}) => DocBlock(
  id: id,
  type: DocBlockType.field,
  field: field,
  zone: zone,
  x: x,
  y: y,
  w: w,
  h: h,
  fontPt: pt,
  bold: bold,
  align: align,
  color: color,
);

DocBlock _img(
  String id,
  DocImageRole role,
  double x,
  double y,
  double w,
  double h, {
  DocAlign align = DocAlign.left,
}) => DocBlock(
  id: id,
  type: DocBlockType.image,
  imageRole: role,
  x: x,
  y: y,
  w: w,
  h: h,
  align: align,
);

DocBlock _line(
  String id,
  double x,
  double y,
  double w, {
  String color = 'accent',
  double stroke = 1.2,
  DocZone zone = DocZone.header,
}) => DocBlock(
  id: id,
  type: DocBlockType.line,
  zone: zone,
  x: x,
  y: y,
  w: w,
  h: 1,
  color: color,
  strokePt: stroke,
);

DocBlock _box(
  String id,
  double x,
  double y,
  double w,
  double h, {
  String fill = 'soft',
  String color = 'border',
  double stroke = 0.6,
  double radius = 2,
}) => DocBlock(
  id: id,
  type: DocBlockType.box,
  x: x,
  y: y,
  w: w,
  h: h,
  fill: fill,
  color: color,
  strokePt: stroke,
  radiusMm: radius,
);

