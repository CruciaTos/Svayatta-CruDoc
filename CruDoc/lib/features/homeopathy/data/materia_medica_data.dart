/// Where a remedy comes from.
enum RemedyGroup {
  plant('Plant'),
  mineral('Mineral'),
  animal('Animal'),
  nosode('Nosode');

  const RemedyGroup(this.label);
  final String label;
}

/// Overall temperature picture of the remedy.
enum RemedyThermal {
  hot('Hot'),
  chilly('Chilly'),
  mixed('Mixed');

  const RemedyThermal(this.label);
  final String label;
}

/// One quick-reference entry. Written as short reminders of the classical
/// keynotes, not a replacement for a full Materia Medica.
class MateriaMedicaEntry {
  const MateriaMedicaEntry({
    required this.name,
    required this.abbr,
    required this.group,
    required this.keynotes,
    required this.mind,
    required this.thermal,
    required this.worse,
    required this.better,
    this.complementary = const [],
    this.followsWell = const [],
    this.inimical = const [],
    this.antidotes = const [],
  });

  final String name;
  final String abbr;
  final RemedyGroup group;
  final List<String> keynotes;

  /// Key mental / emotional picture.
  final String mind;
  final RemedyThermal thermal;
  final String worse;
  final String better;

  /// Remedy names.
  final List<String> complementary;
  final List<String> followsWell;
  final List<String> inimical;
  final List<String> antidotes;

  bool get hasRelationships =>
      complementary.isNotEmpty ||
      followsWell.isNotEmpty ||
      inimical.isNotEmpty ||
      antidotes.isNotEmpty;
}

/// Looks an entry up by full name or abbreviation (case and full stops
/// ignored). Null when the text is not on the list.
MateriaMedicaEntry? materiaMedicaFor(String text) {
  final key = _norm(text);
  if (key.isEmpty) return null;
  for (final e in kMateriaMedica) {
    if (_norm(e.name) == key || _norm(e.abbr) == key) return e;
  }
  return null;
}

String _norm(String s) => s.toLowerCase().replaceAll(RegExp(r'[^a-z0-9]'), '');

